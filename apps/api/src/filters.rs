//! Mail filters: simple "if <field> contains <text>, then <action>" rules.
//!
//! Rules are stored in SQLite (`mail_filters`). Every change rebuilds one
//! Sieve script (`iris-filters`) from all of a mailbox's rules and installs
//! it on the mail server as the active script, so the rules run on new mail
//! at delivery time, even while nobody is signed in. If installing fails,
//! the database change is undone, so the stored rules and the running
//! script stay the same.
use crate::{
    organize, owned_account, valid_message_id, ApiError, ApiResult, AppState, CurrentUser, S,
};
use axum::{
    extract::{Path, State},
    http::StatusCode,
    response::IntoResponse,
    Extension, Json,
};
use iris_auth as auth;
use iris_config::limits::{MAX_FILTERS, MAX_FILTER_VALUE_CHARS};
use iris_mail::CUSTOM_ROLE;
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::collections::HashMap;

#[derive(Debug, Clone, Serialize, sqlx::FromRow)]
pub(crate) struct Rule {
    pub(crate) id: String,
    /// `from`, `to` (To or Cc), or `subject`.
    pub(crate) field: String,
    /// Case-insensitive "contains" text.
    pub(crate) value: String,
    /// `move`, `label`, `star`, or `read`.
    pub(crate) action: String,
    /// move: mailbox id; label: label name; otherwise none.
    pub(crate) target: Option<String>,
}

/// Quotes a Sieve string: backslash and double quote are escaped. Callers
/// never pass control characters (rejected on input).
fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// Builds the Sieve script for `rules`, or `None` when there are none.
///
/// Flag rules (label / star / read) come first and move rules last: a
/// `fileinto` files the message with the flags set so far, and the first
/// matching move ends processing (`stop`), so a message lands in one folder
/// with every flag its rules gave it. `folder_names` maps a move target id
/// to its current name, the fallback `:mailboxid` uses if the id is gone.
pub(crate) fn sieve_script(
    rules: &[Rule],
    folder_names: &HashMap<String, String>,
) -> Option<String> {
    if rules.is_empty() {
        return None;
    }
    let has_move = rules.iter().any(|r| r.action == "move");
    let has_flag = rules.iter().any(|r| r.action != "move");
    let mut require = vec![];
    if has_move {
        require.extend(["\"fileinto\"", "\"mailboxid\""]);
    }
    if has_flag {
        require.push("\"imap4flags\"");
    }
    let mut out = format!(
        "# Generated by IRIS from your filter rules. Changes made here are overwritten.\nrequire [{}];\n",
        require.join(", ")
    );
    let ordered = rules
        .iter()
        .filter(|r| r.action != "move")
        .chain(rules.iter().filter(|r| r.action == "move"));
    for r in ordered {
        let headers = match r.field.as_str() {
            "from" => "\"from\"",
            "to" => "[\"to\", \"cc\"]",
            _ => "\"subject\"",
        };
        let target = r.target.as_deref().unwrap_or_default();
        let action = match r.action.as_str() {
            "label" => format!("addflag {};", quote(target)),
            "star" => "addflag \"\\\\Flagged\";".to_string(),
            "read" => "addflag \"\\\\Seen\";".to_string(),
            _ => {
                let name = folder_names
                    .get(target)
                    .map(String::as_str)
                    .unwrap_or("INBOX");
                format!(
                    "fileinto :mailboxid {} {};\n    stop;",
                    quote(target),
                    quote(name)
                )
            }
        };
        out.push_str(&format!(
            "\nif header :contains {headers} {} {{\n    {action}\n}}\n",
            quote(&r.value)
        ));
    }
    Some(out)
}

async fn rules(s: &AppState, mailbox_id: &str) -> Result<Vec<Rule>, ApiError> {
    Ok(sqlx::query_as::<_, Rule>(
        "SELECT id, field, value, action, target FROM mail_filters WHERE mailbox_id=? ORDER BY created_at, id",
    )
    .bind(mailbox_id)
    .fetch_all(&s.pool)
    .await?)
}

/// True when a rule of `action` points at `target` (a label or folder).
pub(crate) async fn target_in_use(
    s: &AppState,
    mailbox_id: &str,
    action: &str,
    target: &str,
) -> Result<bool, ApiError> {
    let n: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM mail_filters WHERE mailbox_id=? AND action=? AND target=?",
    )
    .bind(mailbox_id)
    .bind(action)
    .bind(target)
    .fetch_one(&s.pool)
    .await?;
    Ok(n > 0)
}

/// Rebuilds and installs the mailbox's Sieve script from the stored rules.
async fn sync(
    s: &AppState,
    u: &CurrentUser,
    account: &str,
    mailbox_id: &str,
) -> Result<(), ApiError> {
    let rules = rules(s, mailbox_id).await?;
    let mut names = HashMap::new();
    if rules.iter().any(|r| r.action == "move") {
        for f in s
            .jmap
            .folders(&u.creds.user, &u.creds.pass, account)
            .await?
        {
            names.insert(f.id, f.name);
        }
    }
    let script = sieve_script(&rules, &names);
    s.jmap
        .put_filter_script(&u.creds.user, &u.creds.pass, account, script.as_deref())
        .await?;
    Ok(())
}

pub(crate) async fn list(
    State(s): S,
    Extension(u): Extension<CurrentUser>,
    Path(mailbox_id): Path<String>,
) -> ApiResult {
    owned_account(&s, &u, &mailbox_id).await?;
    let rules = rules(&s, &mailbox_id).await?;
    Ok(Json(json!({ "filters": rules })).into_response())
}

#[derive(Deserialize)]
pub(crate) struct NewRule {
    field: String,
    value: String,
    action: String,
    target: Option<String>,
}

pub(crate) async fn create(
    State(s): S,
    Extension(u): Extension<CurrentUser>,
    Path(mailbox_id): Path<String>,
    Json(b): Json<NewRule>,
) -> ApiResult {
    let account = owned_account(&s, &u, &mailbox_id).await?;
    let bad = |code| ApiError(StatusCode::BAD_REQUEST, code);
    if !["from", "to", "subject"].contains(&b.field.as_str()) {
        return Err(bad("invalid_filter"));
    }
    let value = b.value.trim().to_string();
    let len = value.chars().count();
    if len == 0 || len > MAX_FILTER_VALUE_CHARS || value.chars().any(char::is_control) {
        return Err(bad("invalid_filter"));
    }
    let target = match b.action.as_str() {
        "star" | "read" => None,
        "label" => {
            let name = organize::clean_label(b.target.as_deref().unwrap_or_default())?;
            if !organize::label_exists(&s, &mailbox_id, &name).await? {
                return Err(ApiError(StatusCode::NOT_FOUND, "unknown_label"));
            }
            Some(name)
        }
        "move" => {
            let id = b.target.unwrap_or_default();
            if !valid_message_id(&id) {
                return Err(bad("invalid_folder"));
            }
            // Only Archive, Trash or a custom folder: filling Inbox is what
            // no filter does, and Sent/Drafts are not for incoming mail.
            let folders = s
                .jmap
                .folders(&u.creds.user, &u.creds.pass, &account)
                .await?;
            let ok = folders.iter().any(|f| {
                f.id == id && ["archive", "trash", CUSTOM_ROLE].contains(&f.role.as_str())
            });
            if !ok {
                return Err(bad("invalid_folder"));
            }
            Some(id)
        }
        _ => return Err(bad("invalid_filter")),
    };
    let id = uuid::Uuid::new_v4().to_string();
    let r = sqlx::query(
        "INSERT INTO mail_filters (id, mailbox_id, field, value, action, target, created_at) \
         SELECT ?, ?, ?, ?, ?, ?, ? WHERE (SELECT COUNT(*) FROM mail_filters WHERE mailbox_id = ?) < ?",
    )
    .bind(&id)
    .bind(&mailbox_id)
    .bind(&b.field)
    .bind(&value)
    .bind(&b.action)
    .bind(&target)
    .bind(auth::now())
    .bind(&mailbox_id)
    .bind(MAX_FILTERS)
    .execute(&s.pool)
    .await?;
    if r.rows_affected() == 0 {
        return Err(ApiError(StatusCode::CONFLICT, "too_many_filters"));
    }
    if let Err(e) = sync(&s, &u, &account, &mailbox_id).await {
        sqlx::query("DELETE FROM mail_filters WHERE id=?")
            .bind(&id)
            .execute(&s.pool)
            .await?;
        return Err(e);
    }
    let rule = Rule {
        id,
        field: b.field,
        value,
        action: b.action,
        target,
    };
    Ok((StatusCode::CREATED, Json(json!({ "filter": rule }))).into_response())
}

pub(crate) async fn delete(
    State(s): S,
    Extension(u): Extension<CurrentUser>,
    Path((mailbox_id, id)): Path<(String, String)>,
) -> ApiResult {
    let account = owned_account(&s, &u, &mailbox_id).await?;
    let row: Option<(String, String, String, Option<String>, String)> = sqlx::query_as(
        "SELECT field, value, action, target, created_at FROM mail_filters WHERE id=? AND mailbox_id=?",
    )
    .bind(&id)
    .bind(&mailbox_id)
    .fetch_optional(&s.pool)
    .await?;
    let Some((field, value, action, target, created_at)) = row else {
        return Err(ApiError(StatusCode::NOT_FOUND, "not_found"));
    };
    sqlx::query("DELETE FROM mail_filters WHERE id=?")
        .bind(&id)
        .execute(&s.pool)
        .await?;
    if let Err(e) = sync(&s, &u, &account, &mailbox_id).await {
        sqlx::query(
            "INSERT INTO mail_filters (id, mailbox_id, field, value, action, target, created_at) VALUES (?,?,?,?,?,?,?)",
        )
        .bind(&id)
        .bind(&mailbox_id)
        .bind(field)
        .bind(value)
        .bind(action)
        .bind(target)
        .bind(created_at)
        .execute(&s.pool)
        .await?;
        return Err(e);
    }
    Ok(StatusCode::NO_CONTENT.into_response())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rule(field: &str, value: &str, action: &str, target: Option<&str>) -> Rule {
        Rule {
            id: "r".into(),
            field: field.into(),
            value: value.into(),
            action: action.into(),
            target: target.map(str::to_string),
        }
    }

    #[test]
    fn no_rules_no_script() {
        assert_eq!(sieve_script(&[], &HashMap::new()), None);
    }

    #[test]
    fn flags_come_before_moves_and_strings_are_escaped() {
        let names = HashMap::from([("mb1".to_string(), "Re\"ceipts".to_string())]);
        let s = sieve_script(
            &[
                rule("from", "billing@shop.test", "move", Some("mb1")),
                rule("subject", "a \"quoted\" \\ text", "label", Some("work")),
                rule("to", "team@", "star", None),
                rule("subject", "newsletter", "read", None),
            ],
            &names,
        )
        .unwrap();
        assert!(s.contains("require [\"fileinto\", \"mailboxid\", \"imap4flags\"];"));
        assert!(s.contains("if header :contains \"subject\" \"a \\\"quoted\\\" \\\\ text\" {\n    addflag \"work\";\n}"));
        assert!(s.contains(
            "if header :contains [\"to\", \"cc\"] \"team@\" {\n    addflag \"\\\\Flagged\";\n}"
        ));
        assert!(s.contains("addflag \"\\\\Seen\";"));
        assert!(s.contains(
            "if header :contains \"from\" \"billing@shop.test\" {\n    fileinto :mailboxid \"mb1\" \"Re\\\"ceipts\";\n    stop;\n}"
        ));
        let label = s.find("addflag \"work\"").unwrap();
        let mv = s.find("fileinto :mailboxid").unwrap();
        assert!(label < mv, "flag rules must run before the move");
    }

    #[test]
    fn only_needed_extensions_are_required() {
        let s = sieve_script(&[rule("from", "x", "star", None)], &HashMap::new()).unwrap();
        assert!(s.contains("require [\"imap4flags\"];"));
        let s = sieve_script(&[rule("from", "x", "move", Some("m"))], &HashMap::new()).unwrap();
        assert!(s.contains("require [\"fileinto\", \"mailboxid\"];"));
    }
}
